/**
 * A small, deliberately limited Markdown renderer.
 *
 * Why not `marked` + `DOMPurify`? Because the blog body is operator-supplied
 * text that ends up inside `dangerouslySetInnerHTML`, and that is exactly the
 * place where a sanitiser bypass becomes stored XSS. This renderer is safe by
 * construction instead of by filtering:
 *
 *   1. **Escape first.** Every `&`, `<`, `>`, `"` and `'` in the source is
 *      escaped before any markup is generated. Raw HTML in the source is
 *      therefore rendered as visible text, never parsed.
 *   2. **Generate second.** Tags only ever come from this file's own string
 *      literals, so the set of possible elements and attributes is fixed.
 *   3. **Attributes are allow-listed.** The only interpolated attribute is a
 *      link `href`, and that is restricted to `http:`, `https:`, `mailto:`
 *      and site-relative paths — so `javascript:` and `data:` URLs cannot
 *      appear.
 *
 * Supported syntax: `##`/`###`/`####` headings, paragraphs, `**bold**`,
 * `*italic*`, `` `code` ``, fenced code blocks, `-`/`*` bullet lists, `1.`
 * numbered lists, `>` blockquotes, `---` rules, and `[text](url)` links.
 */

const ENTITIES: Record<string, string> = {
  "&": "&amp;",
  "<": "&lt;",
  ">": "&gt;",
  '"': "&quot;",
  "'": "&#39;",
};

/** Escape text for safe interpolation into HTML. */
export function escapeHtml(input: string): string {
  return input.replace(/[&<>"']/g, (ch) => ENTITIES[ch] ?? ch);
}

/**
 * Validate a link target. Returns `null` when the URL is not safe to render,
 * in which case the link is rendered as plain text.
 */
function safeHref(raw: string): { href: string; external: boolean } | null {
  const value = raw.trim();
  if (!value || value.length > 2048) return null;
  // Reject control characters and whitespace used to smuggle schemes.
  if (/[\u0000- \u007F<>"'`\\]/.test(value)) return null;

  if (value.startsWith("/") && !value.startsWith("//")) {
    return { href: value, external: false };
  }
  if (value.startsWith("#")) {
    return { href: value, external: false };
  }

  let url: URL;
  try {
    url = new URL(value);
  } catch {
    return null;
  }
  if (url.protocol === "mailto:") return { href: url.href, external: false };
  if (url.protocol !== "http:" && url.protocol !== "https:") return null;
  return { href: url.href, external: true };
}

/**
 * Apply inline formatting to an **already HTML-escaped** string.
 * Order matters: code spans are extracted first so their contents are not
 * re-processed as emphasis.
 */
function renderInline(escaped: string): string {
  const codeSpans: string[] = [];
  let text = escaped.replace(/`([^`\n]+)`/g, (_m, code: string) => {
    const index = codeSpans.push(
      `<code class="rounded bg-ink-900/80 px-1.5 py-0.5 font-mono text-[0.85em] text-brand-200">${code}</code>`,
    ) - 1;
    return `\u0000CODE${index}\u0000`;
  });

  // Links: [label](href)
  text = text.replace(
    /\[([^\]\n]{1,200})\]\(([^)\s]{1,2048})\)/g,
    (_match, label: string, href: string) => {
      // `href` is escaped text; turn &amp; back into & before parsing the URL.
      const decoded = href.replace(/&amp;/g, "&").replace(/&#39;/g, "'").replace(/&quot;/g, '"');
      const link = safeHref(decoded);
      if (!link) return label;
      const attrs = link.external
        ? ' target="_blank" rel="noopener noreferrer nofollow ugc"'
        : "";
      return `<a href="${escapeHtml(link.href)}" class="font-medium text-brand-600 underline decoration-brand-300 underline-offset-2 transition-colors hover:text-brand-700 dark:text-brand-300 dark:hover:text-brand-200"${attrs}>${label}</a>`;
    },
  );

  // Bold, then italic (bold first so ** is not eaten by the * rule).
  text = text.replace(/\*\*([^*\n]{1,200})\*\*/g, "<strong>$1</strong>");
  text = text.replace(/(^|[\s(])\*([^*\n]{1,200})\*(?=[\s).,!?:;]|$)/g, "$1<em>$2</em>");

  // Restore code spans.
  text = text.replace(/\u0000CODE(\d+)\u0000/g, (_m, i: string) => codeSpans[Number(i)] ?? "");

  return text;
}

type Block =
  | { kind: "p"; lines: string[] }
  | { kind: "h"; level: 2 | 3 | 4; text: string }
  | { kind: "ul"; items: string[] }
  | { kind: "ol"; items: string[] }
  | { kind: "quote"; lines: string[] }
  | { kind: "code"; lines: string[] }
  | { kind: "hr" };

/**
 * Render Markdown to a safe HTML string.
 *
 * The result contains only elements and classes generated by this module and
 * is safe to pass to `dangerouslySetInnerHTML`.
 */
export function renderMarkdown(source: string): string {
  if (typeof source !== "string" || source.trim() === "") return "";

  // Cap the input so a pathological document cannot stall rendering.
  const normalised = source.replace(/\r\n?/g, "\n").slice(0, 100_000);
  const lines = normalised.split("\n");

  const blocks: Block[] = [];
  let inFence = false;

  for (const rawLine of lines) {
    const line = rawLine.replace(/\s+$/, "");

    // Fenced code block
    if (/^\s*```/.test(line)) {
      if (inFence) {
        inFence = false;
      } else {
        inFence = true;
        blocks.push({ kind: "code", lines: [] });
      }
      continue;
    }
    if (inFence) {
      const current = blocks[blocks.length - 1];
      if (current?.kind === "code") current.lines.push(rawLine);
      continue;
    }

    // Blank line closes any open block
    if (line.trim() === "") {
      if (blocks[blocks.length - 1]?.kind !== undefined) {
        blocks.push({ kind: "p", lines: [] });
      }
      continue;
    }

    // Horizontal rule
    if (/^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(line)) {
      blocks.push({ kind: "hr" });
      continue;
    }

    // Heading (h1 is reserved for the page title, so #/## both map to h2)
    const heading = /^(#{1,6})\s+(.*)$/.exec(line);
    if (heading) {
      const hashes = heading[1]!.length;
      const level = hashes <= 2 ? 2 : hashes === 3 ? 3 : 4;
      blocks.push({ kind: "h", level: level as 2 | 3 | 4, text: heading[2]!.trim() });
      continue;
    }

    // Blockquote
    const quote = /^\s*>\s?(.*)$/.exec(line);
    if (quote) {
      const last = blocks[blocks.length - 1];
      if (last?.kind === "quote") last.lines.push(quote[1]!);
      else blocks.push({ kind: "quote", lines: [quote[1]!] });
      continue;
    }

    // Bullet list
    const bullet = /^\s*[-*+]\s+(.*)$/.exec(line);
    if (bullet) {
      const last = blocks[blocks.length - 1];
      if (last?.kind === "ul") last.items.push(bullet[1]!);
      else blocks.push({ kind: "ul", items: [bullet[1]!] });
      continue;
    }

    // Numbered list
    const numbered = /^\s*\d{1,3}[.)]\s+(.*)$/.exec(line);
    if (numbered) {
      const last = blocks[blocks.length - 1];
      if (last?.kind === "ol") last.items.push(numbered[1]!);
      else blocks.push({ kind: "ol", items: [numbered[1]!] });
      continue;
    }

    // Paragraph text
    const last = blocks[blocks.length - 1];
    if (last?.kind === "p") last.lines.push(line.trim());
    else blocks.push({ kind: "p", lines: [line.trim()] });
  }

  const out: string[] = [];

  for (const block of blocks) {
    switch (block.kind) {
      case "hr":
        out.push('<hr class="my-10 border-ink-200 dark:border-ink-800" />');
        break;

      case "h": {
        const inner = renderInline(escapeHtml(block.text));
        const id = headingId(block.text);
        const cls =
          block.level === 2
            ? "mt-12 mb-4 scroll-mt-28 text-2xl font-semibold tracking-tight text-ink-900 sm:text-3xl dark:text-white"
            : block.level === 3
              ? "mt-9 mb-3 scroll-mt-28 text-xl font-semibold tracking-tight text-ink-900 dark:text-white"
              : "mt-7 mb-2 scroll-mt-28 text-lg font-semibold text-ink-900 dark:text-white";
        out.push(`<h${block.level} id="${escapeHtml(id)}" class="${cls}">${inner}</h${block.level}>`);
        break;
      }

      case "p": {
        const text = block.lines.join(" ").trim();
        if (!text) break;
        out.push(
          `<p class="my-5 leading-[1.75] text-ink-700 dark:text-ink-200">${renderInline(escapeHtml(text))}</p>`,
        );
        break;
      }

      case "ul": {
        const items = block.items
          .map((item) => `<li class="pl-1">${renderInline(escapeHtml(item))}</li>`)
          .join("");
        out.push(
          `<ul class="my-5 list-disc space-y-2 pl-6 text-ink-700 marker:text-brand-500 dark:text-ink-200">${items}</ul>`,
        );
        break;
      }

      case "ol": {
        const items = block.items
          .map((item) => `<li class="pl-1">${renderInline(escapeHtml(item))}</li>`)
          .join("");
        out.push(
          `<ol class="my-5 list-decimal space-y-2 pl-6 text-ink-700 marker:font-semibold marker:text-brand-500 dark:text-ink-200">${items}</ol>`,
        );
        break;
      }

      case "quote": {
        const text = block.lines.join(" ").trim();
        if (!text) break;
        out.push(
          `<blockquote class="my-7 border-l-4 border-brand-400 bg-brand-50/60 py-3 pl-5 pr-4 text-lg italic text-ink-800 dark:bg-brand-950/30 dark:text-ink-100">${renderInline(escapeHtml(text))}</blockquote>`,
        );
        break;
      }

      case "code": {
        const code = escapeHtml(block.lines.join("\n"));
        if (!code.trim()) break;
        out.push(
          `<pre class="my-7 overflow-x-auto rounded-2xl bg-ink-950 p-5 text-sm leading-relaxed text-ink-100 ring-1 ring-ink-800"><code class="font-mono">${code}</code></pre>`,
        );
        break;
      }
    }
  }

  return out.join("\n");
}

/** Stable, URL-safe id for in-page heading anchors. */
function headingId(text: string): string {
  return (
    text
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[̀-ͯ]/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 60) || "section"
  );
}

/** Extract `##`-level headings so a post can render a table of contents. */
export function extractHeadings(source: string): { id: string; text: string }[] {
  if (typeof source !== "string") return [];
  const result: { id: string; text: string }[] = [];
  let inFence = false;
  for (const line of source.replace(/\r\n?/g, "\n").split("\n")) {
    if (/^\s*```/.test(line)) {
      inFence = !inFence;
      continue;
    }
    if (inFence) continue;
    const match = /^(#{1,2})\s+(.*)$/.exec(line);
    if (match) {
      const text = match[2]!.trim().replace(/[*`_]/g, "");
      if (text) result.push({ id: headingId(text), text });
    }
  }
  return result.slice(0, 12);
}

/** Plain-text summary used for meta descriptions and list previews. */
export function toPlainText(source: string, maxLength = 200): string {
  if (typeof source !== "string") return "";
  const text = source
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/`([^`]*)`/g, "$1")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/^\s{0,3}#{1,6}\s+/gm, "")
    .replace(/^\s{0,3}>\s?/gm, "")
    .replace(/^\s*[-*+]\s+/gm, "")
    .replace(/^\s*\d{1,3}[.)]\s+/gm, "")
    .replace(/[*_~]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (text.length <= maxLength) return text;
  const cut = text.slice(0, maxLength);
  const lastSpace = cut.lastIndexOf(" ");
  return `${(lastSpace > maxLength * 0.6 ? cut.slice(0, lastSpace) : cut).trimEnd()}…`;
}

/** Rough reading time in minutes, at 220 words per minute. */
export function readingTimeMinutes(source: string): number {
  const words = toPlainText(source, 100_000).split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / 220));
}
